async (page) => {
  if (!page.url().startsWith('http://127.0.0.1:5362/')) throw new Error('Isolated finance Excel fixture required');
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const dialog=()=>page.getByRole('dialog',{name:'导入成本表',exact:true});
  const waitCosts=()=>page.waitForResponse(r=>r.url().includes('/finance/costs?')&&r.ok());
  const saved=[];page.on('request',r=>{if(r.url().endsWith('/finance/costs/save'))saved.push(r.postDataJSON());});
  await page.setViewportSize({width:1440,height:1000});
  await Promise.all([waitCosts(),page.getByRole('button',{name:'商品成本',exact:true}).click()]);
  await page.locator('.finance-panel .el-loading-mask').waitFor({state:'hidden'});
  const amount=page.getByRole('spinbutton',{name:'GT-2026 成本',exact:true});
  const zero=page.getByRole('spinbutton',{name:'GT-OTHER 成本',exact:true});
  check(await amount.inputValue()==='18.00'&&await zero.inputValue()==='','Fixture has saved and missing costs');
  const keyword=page.locator('.finance-cost-filters .el-input input').nth(1);
  await keyword.fill('GT-2026-1');
  check(await page.getByRole('button',{name:'导出成本表',exact:true}).isDisabled(),'Changed filters block exports');
  await Promise.all([waitCosts(),page.getByRole('button',{name:'查询',exact:true}).click()]);
  const pendingDownload=page.waitForEvent('download');
  const exported=page.waitForRequest(r=>r.url().endsWith('/finance/costs/export'));
  await page.getByRole('button',{name:'导出成本表',exact:true}).click();
  check((await exported).postDataJSON().keyword==='GT-2026-1','Export uses confirmed filters');
  await (await pendingDownload).saveAs('output/playwright/finance-cost-filtered-export.xlsx');
  await keyword.fill('');await Promise.all([waitCosts(),page.getByRole('button',{name:'查询',exact:true}).click()]);
  await page.locator('.finance-panel .el-loading-mask').waitFor({state:'hidden'});
  await amount.fill('19');await amount.press('Tab');
  await page.getByRole('button',{name:'导入成本表',exact:true}).click();
  await page.getByText('有未保存的成本修改，请先保存，或手动撤销修改后再导入。当前草稿已保留。',{exact:true}).waitFor();
  check(await dialog().count()===0&&await amount.inputValue()==='19.00','Import never overwrites page drafts');
  await page.getByText('有未保存的成本修改，请先保存，或手动撤销修改后再导入。当前草稿已保留。',{exact:true}).waitFor({state:'hidden'});
  await amount.fill('18');await amount.press('Tab');
  await page.getByRole('button',{name:'导入成本表',exact:true}).click();
  async function upload(path){
    const wait=page.waitForResponse(r=>r.url().endsWith('/finance/costs/import/preview'));
    await dialog().getByLabel('选择成本表文件').setInputFiles(path);
    const response=await wait;check(response.ok(),'Workbook preview succeeds');return response.json();
  }
  let data=await upload('output/playwright/cost-excel-valid.xlsx');
  check(data.summary.update===1&&data.summary.blank===1&&data.summary.same===1&&!data.summary.error,'Blank, equal and explicit zero distinguished');
  check(saved.length===0,'Preview does not save');
  await dialog().getByRole('button',{name:'取消',exact:true}).click();
  check(saved.length===0&&await zero.inputValue()==='','Cancel preview leaves current costs unchanged');
  await page.getByRole('button',{name:'导入成本表',exact:true}).click();
  data=await upload('output/playwright/cost-excel-invalid.xlsx');
  check(data.summary.error===1,'Formula rejected with a row result');
  await dialog().getByText('新成本不支持公式，请填写金额',{exact:true}).waitFor();
  check(await dialog().getByRole('button',{name:'确认保存',exact:true}).isDisabled(),'Errors prevent whole-batch saving');
  data=await upload('output/playwright/cost-excel-valid.xlsx');
  await dialog().getByRole('button',{name:'确认保存',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/finance-cost-excel-preview-desktop.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page has no horizontal overflow');
  check(await dialog().getByRole('button',{name:'确认保存',exact:true}).isVisible(),'Mobile confirmation remains reachable');
  await page.screenshot({path:'output/playwright/finance-cost-excel-preview-mobile.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:1440,height:1000});
  let lost=false;
  await page.route('**/api/admin/finance/costs/save',async route=>{if(!lost){lost=true;await route.fetch();await route.abort('failed');}else await route.continue();});
  await dialog().getByRole('button',{name:'确认保存',exact:true}).click();
  await dialog().getByText('连接失败，请检查网络后重试。当前输入已保留。',{exact:true}).waitFor();
  check(await dialog().getByRole('button',{name:'确认保存',exact:true}).isEnabled(),'Lost response retains exact submission for retry');
  const replay=page.waitForResponse(r=>r.url().endsWith('/finance/costs/save'));
  await dialog().getByRole('button',{name:'确认保存',exact:true}).click();
  check((await (await replay).json()).replayed===true,'Retry uses original request ID');
  await dialog().waitFor({state:'hidden'});await page.locator('.finance-panel .el-loading-mask').waitFor({state:'hidden'});
  check(saved.length===2&&saved[0].requestId===saved[1].requestId,'No duplicate submission identity');
  check(await zero.inputValue()==='0.00','Explicit zero saved and reloaded');
  await page.unroute('**/api/admin/finance/costs/save');
  await page.getByRole('button',{name:'导入成本表',exact:true}).click();
  data=await upload('output/playwright/cost-excel-valid.xlsx');
  check(data.summary.error===1&&!data.previewHash,'Old workbook cannot overwrite a newer version');
  check(await dialog().getByRole('button',{name:'确认保存',exact:true}).isDisabled(),'Version conflicts block confirmation');
  await dialog().getByRole('button',{name:'取消',exact:true}).click();
  return {costExcelBrowser:true,confirmedFilters:true,draftProtected:true,blankSameZero:true,cancelReadOnly:true,
    formulaRowError:true,atomicConflict:true,idempotentRetry:true,desktopAndMobile:true};
}
