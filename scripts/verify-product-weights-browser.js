// Browser lifecycle uses only the explicitly guarded port 5360 *_test fixture.
async (page) => {
  if (!page.url().startsWith('http://127.0.0.1:5360/')) throw new Error('Isolated fixture required');
  const check=(ok,message)=>{if(!ok) throw new Error(message);};
  const settleDrawer=()=>page.waitForFunction(()=>[...document.querySelectorAll('.el-drawer')].some(el=>el.offsetWidth&&el.getBoundingClientRect().right<=window.innerWidth+1&&getComputedStyle(el).opacity==='1'));
  const api=(path,body)=>page.evaluate(async ({path,body})=>{
    const response=await fetch('/api/admin/'+path,{method:body?'POST':'GET',headers:{Authorization:'Bearer '+localStorage.getItem('lumiere-admin-token'),'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
    if(!response.ok) throw new Error('Fixture API '+path+': '+response.status);
    return response.json();
  },{path,body});
  const weight=(color,size)=>page.getByRole('spinbutton',{name:`${color} ${size} 单件净重（g）`,exact:true});
  const choose=async (code)=>{
    await page.locator('.weight-bulk-tools .el-select').click();
    await page.getByRole('option',{name:code,exact:true}).click();
  };
  const apply=async (value)=>{
    await page.getByRole('spinbutton',{name:'批量单件净重（g）',exact:true}).fill(String(value));
    await page.getByRole('spinbutton',{name:'批量单件净重（g）',exact:true}).press('Tab');
    await page.getByRole('button',{name:'批量应用重量',exact:true}).click();
  };
  await page.setViewportSize({width:1920,height:1080});
  await page.goto('http://127.0.0.1:5360/products');
  await page.getByRole('button',{name:'编辑',exact:true}).first().waitFor();
  check(await page.getByRole('columnheader',{name:'推荐',exact:true}).count()===0,'Product recommendation column remains');
  // Old per-account column preferences must not restore a removed column.
  await page.evaluate(()=>{
    const key=Object.keys(localStorage).find(k=>k.startsWith('gingtto-table:')&&k.endsWith(':products'));
    if(!key) throw new Error('Product table settings missing');
    const settings=JSON.parse(localStorage.getItem(key));
    settings.visible=[...new Set([...settings.visible,'featured'])];
    localStorage.setItem(key,JSON.stringify(settings));
  });
  await page.reload();
  await page.getByRole('button',{name:'编辑',exact:true}).first().waitFor();
  check(await page.getByRole('columnheader',{name:'推荐',exact:true}).count()===0,'Cached preferences restored recommendation column');
  await page.getByRole('button',{name:'显示列',exact:true}).click();
  check(await page.getByRole('checkbox',{name:'推荐',exact:true}).count()===0,'Column picker still offers recommendation');
  await page.getByRole('button',{name:'显示列',exact:true}).click();
  await page.screenshot({path:'output/playwright/products-no-recommendation-column.png'});
  await page.getByRole('button',{name:'编辑',exact:true}).first().click();
  await weight('深靛蓝','M').waitFor();
  check(await weight('深靛蓝','M').inputValue()==='350','Existing weight missing');
  await choose('M');await apply(410);
  const confirm=page.getByRole('dialog',{name:'确认操作'});
  await confirm.waitFor();
  check((await confirm.innerText()).includes('2 个已填重量'),'Overwrite count missing');
  await confirm.getByRole('button',{name:'取消',exact:true}).click();
  check(await weight('深靛蓝','M').inputValue()==='350','Cancelled overwrite changed draft');
  await apply(410);await confirm.getByRole('button',{name:'确认',exact:true}).click();
  for(const color of ['深靛蓝','水洗灰','经典黑']) check(await weight(color,'M').inputValue()==='410','Selected real size not applied');
  check(await weight('深靛蓝','L').inputValue()==='','Unselected size changed');
  check(await weight('经典黑','L').count()===0,'Bulk tool recreated missing size');
  check((await api('products/1')).product.sizePrices.find(s=>s.sizeCode==='M').weightGrams===350,'Draft prematurely saved');
  await choose('全部尺码');await apply(500);await confirm.getByRole('button',{name:'确认',exact:true}).click();
  check((await page.locator('#sizes input[role=spinbutton][aria-label$="单件净重（g）"]').evaluateAll(nodes=>nodes.map(n=>n.value))).every(v=>v==='500'),'All-size application failed');
  await page.getByRole('button',{name:'＋ 添加颜色',exact:true}).click();
  check(await weight('未命名颜色','M').inputValue()==='','New color inherited weight');
  await page.getByRole('button',{name:'移除此颜色',exact:true}).click();
  await page.getByRole('textbox',{name:'新增真实尺码，如 Tall XL',exact:true}).fill('30/M');
  await page.getByRole('button',{name:'添加到所有颜色',exact:true}).click();
  check(await weight('深靛蓝','30/M').inputValue()==='','New real size inherited weight');
  await choose('30/M');await apply(400);
  for(const color of ['深靛蓝','水洗灰','经典黑']) check(await weight(color,'30/M').inputValue()==='400','New real size not selectable');
  await weight('深靛蓝','M').fill('');await weight('深靛蓝','M').press('Tab');
  await page.locator('#sizes').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>!document.querySelector('.el-message'));
  await page.screenshot({path:'output/playwright/product-weights-editor-desktop.png'});
  const save=page.waitForResponse(r=>r.url().endsWith('/api/admin/products/save-group')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'保存商品',exact:true}).click();
  check((await save).status()===200,'Save product failed');await page.waitForURL(url=>url.pathname==='/products');
  check((await api('products/1')).product.sizePrices.find(s=>s.sizeCode==='M').weightGrams===null,'Individual clear not persisted');
  await page.getByRole('button',{name:'编辑',exact:true}).first().click();
  await weight('深靛蓝','M').waitFor();
  check(await weight('深靛蓝','M').inputValue()==='','Cleared weight not retained on reopen');
  check(await weight('深靛蓝','30/M').inputValue()==='400','Weight not retained on reopen');
  await page.getByRole('button',{name:'收起导航',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-testid="weight-bulk-tools"]').scrollIntoViewIfNeeded();
  check(await page.locator('[data-testid="weight-bulk-tools"]').evaluate(el=>el.getBoundingClientRect().right<=window.innerWidth+1),'Bulk toolbar overflows narrow viewport');
  await page.screenshot({path:'output/playwright/product-weights-editor-mobile.png'});
  await page.setViewportSize({width:1920,height:1080});
  await page.getByRole('button',{name:'展开导航',exact:true}).click();
  await page.getByRole('link',{name:'订单管理',exact:true}).click();
  await page.getByRole('button',{name:'订单详情',exact:true}).first().waitFor();
  check(await page.getByRole('columnheader',{name:/净重/}).count()===0,'Order list exposes weight');
  await page.getByRole('button',{name:'显示列',exact:true}).click();
  check(await page.getByRole('checkbox',{name:/净重/}).count()===0,'Order list offers weight column');
  await page.getByRole('button',{name:'显示列',exact:true}).click();
  await page.getByRole('button',{name:'订单详情',exact:true}).first().click();
  const drawer=page.getByRole('dialog');const summary=drawer.locator('[data-testid="order-weight-summary"]');
  await summary.waitFor();
  await settleDrawer();
  check((await summary.innerText()).includes('已知净重 0.500 kg，另有 2 件'),'Partial weight not labelled');
  check(await drawer.getByRole('columnheader',{name:'单件净重（g）',exact:true}).count()===1,'Unit weight missing');
  check(await drawer.getByRole('columnheader',{name:'净重小计（kg）',exact:true}).count()===0,'Line subtotal column remains');
  await page.screenshot({path:'output/playwright/order-weights-partial.png'});
  const update=async grams=>{
    const row=(await api('products/1')).product;
    row.title=row.name.zh||row.name.en;row.familyCode=row.colorGroup;
    row.sizePrices.find(s=>s.sizeCode==='M').weightGrams=grams;
    await api('products/save-group',{products:[row],versions:{[row.id]:row.version}});
  };
  await update(600);
  await drawer.getByRole('button',{name:'刷新详情',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="order-weight-summary"]')?.textContent.includes('1.700 kg'));
  await page.screenshot({path:'output/playwright/order-weights-complete.png'});
  await drawer.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'＋ 新增订单',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  const creationSummary=page.getByRole('dialog').locator('[data-testid="order-goods-summary"]');
  await creationSummary.waitFor();
  check(await creationSummary.locator('[data-testid="order-draft-weight"]').count()===1,'Creation weight summary missing from goods area');
  check(await creationSummary.getByRole('spinbutton',{name:'运费（USD）',exact:true}).count()===1,'Shipping fee missing from goods area');
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click();
  await page.locator('.profile-button').click();
  await page.getByRole('menuitem',{name:'退出登录',exact:true}).click();await page.waitForURL(url=>url.pathname==='/login');
  await page.getByRole('textbox',{name:'账号 / 邮箱'}).fill('warehouse@gingtto.test');
  await page.getByRole('textbox',{name:'密码',exact:true}).fill('Workbench-Test-2026');
  await page.getByRole('button',{name:'登录工作台',exact:true}).click();await page.waitForURL(url=>url.pathname==='/orders');
  await page.getByRole('button',{name:'订单详情',exact:true}).first().click();
  await summary.waitFor();
  await settleDrawer();
  check((await summary.innerText()).includes('1.700 kg'),'Warehouse cannot see weight');
  check(await drawer.getByRole('columnheader',{name:'单价',exact:true}).count()===0,'Warehouse sees prices');
  check(await drawer.getByRole('columnheader',{name:'金额',exact:true}).count()===0,'Warehouse sees amounts');
  check(await drawer.getByRole('columnheader',{name:'单件净重（g）',exact:true}).count()===1,'Warehouse unit weight missing');
  check(await drawer.getByRole('columnheader',{name:'净重小计（kg）',exact:true}).count()===0,'Warehouse line subtotal column remains');
  await page.screenshot({path:'output/playwright/order-weights-warehouse.png'});
  return {noRecommendationColumn:true,realSizeBulk:true,allSizeBulk:true,overwriteConfirm:true,draftOnly:true,individualClear:true,reopen:true,missingSizeNotCreated:true,newWeightsUnset:true,narrowScreen:true,currentWeightRefresh:true,partialSummary:true,listHidden:true,creationWeightSummary:true,lineSubtotalHidden:true,warehouseWeightWithoutMoney:true};
}
