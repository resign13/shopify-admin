"""Canonical order numbers. Keep identical in both applications."""
from datetime import timedelta, timezone
import re
import unicodedata

BEIJING = timezone(timedelta(hours=8))


def make_order_number(order_id, created_at, contact_name):
    return f"LM-{int(order_id):06d}"


def secondary_order_number(value):
    if value is None:
        return ''
    if not isinstance(value, str):
        raise ValueError('副单号格式无效')
    value = value.strip()
    suffix = value[2:] if value[:2].upper() == 'PO' else value
    suffix = suffix.strip()
    if not suffix:
        return ''
    number = 'PO' + suffix
    if len(number) > 255 or any(unicodedata.category(ch).startswith('C') for ch in number):
        raise ValueError('副单号最多 255 个字符，且不包含控制字符')
    return number


def export_label(order):
    return str(order.get('orderNo') or '') + ('\n' + order['secondaryOrderNo'] if order.get('secondaryOrderNo') else '')


def migrate(cur):
    # Only widen old schemas. Repeated startup neither rewrites numbers nor
    # obtains another ALTER lock on an already compatible column.
    cur.execute("""DO $$ BEGIN
      IF EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema=current_schema() AND table_name='orders'
          AND column_name='order_no' AND character_maximum_length < 255) THEN
        ALTER TABLE orders ALTER COLUMN order_no TYPE VARCHAR(255);
      END IF;
    END $$""")
    cur.execute("ALTER TABLE orders ADD COLUMN IF NOT EXISTS secondary_order_no VARCHAR(255) NOT NULL DEFAULT ''")
    # Convert only numbers generated by the previous PO rule (suffix matches ID).
    # No sequence reset, business balance update or history-number deletion.
    cur.execute("SELECT pg_advisory_xact_lock(7192035)")
    cur.execute("""SELECT id,order_no,secondary_order_no FROM orders
      WHERE order_no ~ '^PO[0-9]{4}-.+-[0-9]{6,}$'
        AND substring(order_no from '([0-9]{6,})$')::numeric=id ORDER BY id FOR UPDATE""")
    rows = cur.fetchall()
    for row in rows:
        primary = make_order_number(row['id'], None, None)
        cur.execute('SELECT id FROM orders WHERE order_no=%s AND id<>%s', (primary,row['id']))
        if cur.fetchone():
            raise ValueError('LM 主单号迁移存在冲突，请核对原编号映射')
        if row['secondary_order_no'] not in ('', row['order_no']):
            raise ValueError('原 PO 单号与已有副单号存在冲突，请核对后再迁移')
        cur.execute('UPDATE orders SET order_no=%s,secondary_order_no=%s,updated_at=clock_timestamp() WHERE id=%s',
                    (primary,row['order_no'],row['id']))


def sheet_title(number):
    match = re.fullmatch(r'(PO[0-9]{4})-(.+)-([0-9]{6,})', str(number), re.DOTALL)
    return f'{match[1]}-{match[3]}' if match else str(number)


def display_width(text):
    return sum(0 if unicodedata.combining(ch) else 2 if unicodedata.east_asian_width(ch) in {'W','F'} else 1 for ch in str(text))


def wrapped_lines(text, width):
    return sum(max(1, (display_width(line) + width - 1) // width) for line in str(text).split('\n'))
